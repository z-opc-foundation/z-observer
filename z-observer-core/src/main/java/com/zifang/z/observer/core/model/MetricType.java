package com.zifang.z.observer.core.model;

/**
 * 指标类型。
 *
 * <p>这四种的聚合语义完全不同，选错会让查询结果「看起来有值、其实算错」，所以它们不是
 * 存储上的一个类型字段，而是要被查询引擎分别对待的四套逻辑。
 */
public enum MetricType {

    /**
     * 计数器，只增不减。用于「总共发生多少次」。
     *
     * <p>注意：进程重启会归零，重启本身要能被识别 —— 否则 rate() 会算出一个巨大的负值或
     * 离谱的正值。查询引擎必须做 reset 检测（业界通用的做法是对相邻两点做启发式判断）。
     */
    COUNTER,

    /**
     * 瞬时值，可升可降。用于「现在有多少」「当前是多少」。
     *
     * <p>用法上有个常见错误：把「队列长度」这种只增不减的量注册成 gauge。gauge 不做 reset
     * 检测，所以历史曲线会平白多出一条向下的直线上帝视角的断崖。
     */
    GAUGE,

    /**
     * 直方图。只记录分布（各桶计数 + 总数 + 和），不记录每个原始值。
     *
     * <p>延迟必须用直方图而不是 gauge 记「当前延迟」—— 后者算不出 P99，只有一个瞬时值。
     * 分位数是用分桶数据反解出来的，所以桶边界一旦定死就不能改：改了等于换了指标，
     * 旧数据接不上。这是配桶最常踩的坑，桶边界应当与 p99 目标对齐而不是拍脑袋等分。
     */
    HISTOGRAM,

    /**
     * 摘要。直接记录分位数（客户端侧计算）。优点是不用等收端聚合就能算 P99，
     * 缺点是分位数不可跨实例聚合 —— 三个实例的 P99 的 P99 没有意义。
     * 需要全局分位数时应当改用 HISTOGRAM。
     */
    SUMMARY
}